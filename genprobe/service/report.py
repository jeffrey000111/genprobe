"""Tables for results/service/summary.md from the bench and load-test JSON lines (D-040).

    python -m genprobe.service.report > results/service/summary.md
"""

from __future__ import annotations

import argparse
import glob
import json
import math
import sys
from pathlib import Path

from .loadtest import RateResult, markdown


def _rows(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text().splitlines() if x.strip()] if path.exists() else []


def bench_table(rows: list[dict]) -> str:
    out = ["| metric | device | host CPUs / torch threads | batch size | images/s | median s per batch |",
           "| --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        dev = r["device"] + (f" ({r['gpu']})" if r.get("gpu") else "")
        out.append(f"| {r['metric']} | {dev} | {r['cpus']} / {r['torch_threads']} | {r['batch_size']} | "
                   f"{r['images_per_second']:.2f} | {r['batch_seconds_median']:.3f} |")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dir", default="results/service")
    a = ap.parse_args(argv)
    d = Path(a.dir)
    print("# Scoring service: measurements\n")
    print("Generated by `python -m genprobe.service.report` from the JSON lines in this folder. Setup and "
          "method: docs/service.md and D-040. Each load-test row is one offered rate held for its duration "
          "(open loop, Poisson arrivals, a fresh image per request); end-to-end latency is submit to "
          "score, from the server's timestamps; done/s is completed jobs over the whole run, tail "
          "included.\n")
    for f in sorted(glob.glob(str(d / "bench*.jsonl"))):
        rows = _rows(Path(f))
        if rows:
            print(f"## Scorer throughput (`{Path(f).name}`)\n")
            print(bench_table(rows) + "\n")
    ch = _rows(d / "chaos.jsonl")
    if ch:
        print("## Killing workers mid-batch (`chaos.jsonl`, `python -m genprobe.service.chaos`)\n")
        print("| jobs | workers | batch | lease s | workers killed (SIGKILL) | done | failed | unfinished | "
              "attempts 1 / 2 / 3 | wrong values | seconds |")
        print("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for r in ch:
            at = r["attempts"]
            print(f"| {r['jobs']} | {r['workers']} | {r['batch_size']} | {r['lease_seconds']:g} | {r['workers_killed']} | "
                  f"{r['done']} | {r['failed']} | {r['unfinished']} | {at.get('1', 0)} / {at.get('2', 0)} / "
                  f"{at.get('3', 0)} | {r['wrong_values']} | {r['seconds']} |")
        print()
    lt = _rows(d / "loadtest.jsonl")
    if lt:
        print("## Load tests (`loadtest.jsonl`)\n")
        rows = [RateResult(**{k: (math.nan if v is None else v) for k, v in r.items()}) for r in lt]
        print(markdown(rows) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
